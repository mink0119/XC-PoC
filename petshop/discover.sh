call() {
  label=$1
  shift
  printf '\n======== %s ========\n' "$label"
  curl -v --resolve "$RESOLVE" "$@"
  printf '\n'
}

run() {
  method=$1
  path=$2
  body=$3
  if [ -n "$body" ]; then
    call "$method $path" -X "$method" -H "Content-Type: application/json" -d "$body" "$BASE$path"
  elif [ "$method" = "GET" ]; then
    call "$method $path" "$BASE$path"
  else
    call "$method $path" -X "$method" "$BASE$path"
  fi
}

